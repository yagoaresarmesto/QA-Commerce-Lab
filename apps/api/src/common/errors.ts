export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode];

export interface ValidationDetail {
  field: string;
  message: string;
}

export class AppException extends HttpException {
  constructor(
    status: HttpStatus | number,
    public readonly code: ErrorCode | string,
    message: string,
    public readonly details?: unknown,
  ) {
    super({ code, message, details }, status);
  }
}

// Convenience factories --------------------------------------------------------
export const badRequest = (code: ErrorCode, message: string, details?: unknown) =>
  new AppException(HttpStatus.BAD_REQUEST, code, message, details);
export const unauthorized = (code: ErrorCode, message: string, details?: unknown) =>
  new AppException(HttpStatus.UNAUTHORIZED, code, message, details);
export const forbidden = (code: ErrorCode, message: string, details?: unknown) =>
  new AppException(HttpStatus.FORBIDDEN, code, message, details);
export const notFound = (code: ErrorCode, message: string, details?: unknown) =>
  new AppException(HttpStatus.NOT_FOUND, code, message, details);
export const conflict = (code: ErrorCode, message: string, details?: unknown) =>
  new AppException(HttpStatus.CONFLICT, code, message, details);
export const unprocessable = (code: ErrorCode, message: string, details?: unknown) =>
  new AppException(HttpStatus.UNPROCESSABLE_ENTITY, code, message, details);
